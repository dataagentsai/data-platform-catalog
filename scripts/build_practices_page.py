"""Write the engineering best-practices page from the catalog (decision D12). The page is never edited by hand.

    uv run scripts/build_practices_page.py                          # write every target (see below)
    uv run scripts/build_practices_page.py --check                  # exit 1 if a target differs from the catalog
    uv run scripts/build_practices_page.py --out FILE [--client NAME]   # write one file only

The page names no client unless told to. A client name is a setting, never part of the template or the catalog:
`--client NAME` for one file, or a `client:` on a target in `page-targets.local.yaml` at the repository root (not
committed; see `page-targets.example.yaml`). Without that file the only target is ~/Engineering-Best-Practices.html.

Inputs: practices/*.yaml, practices/proposed-checks.yaml, dac/obligations/, adr/ (titles of the ADRs the practices
cite) and the shift-left bundle's catalog (check titles and stages). Layout and page logic:
scripts/templates/best-practices.html.
"""
import html
import json
import sys
from pathlib import Path

import yaml

from lint import ROOT, load_obligations
from lint_practices import bundle_dir, load_bundle, load_part, load_practices
from lint_shape import load_adrs

TEMPLATE = ROOT / "scripts" / "templates" / "best-practices.html"
SETTINGS = ROOT / "page-targets.local.yaml"
DEFAULT_TARGETS = [(Path.home() / "Engineering-Best-Practices.html", None)]
ADR_BASE = "https://github.com/dataagentsai/data-platform-catalog/blob/main/adr/"


def load_targets(path=SETTINGS):
    """[(file, client name or None)] from the local settings file, or the default target when there is none."""
    if not path.exists():
        return list(DEFAULT_TARGETS)
    out = []
    for i, t in enumerate(yaml.safe_load(path.read_text()) or []):
        if not isinstance(t, dict) or not t.get("path") or set(t) - {"path", "client"}:
            raise SystemExit(f"{path.name}: entry {i + 1} must be {{path: FILE, client: NAME (optional)}}")
        out.append((Path(t["path"]).expanduser(), t.get("client") or None))
    return out


TARGETS = load_targets()
KIND = {"principle": "P", "practice": "B", "anti-pattern": "A"}
LAYER = {"landing": "L", "bronze": "B", "silver": "S", "gold": "G", "semantic": "M", "platform": "X"}


def js(obj):
    return json.dumps(obj, ensure_ascii=False, separators=(",", ":"))


def entry(r, proposed):
    enforced = []
    for e in r["enforced_by"]:
        (k, v), = e.items()
        if k == "shift_left":
            enforced.append({"type": "shift-left", "ids": v})
        elif k == "proposed":
            enforced.append({"type": "gap", "id": v, "text": proposed[v]["title"]})
        else:
            enforced.append({"type": k, "text": v})
    out = {"id": r["id"], "k": KIND[r["kind"]], "t": r["title"], "l": " ".join(LAYER[x] for x in r["layers"]),
           "c": " ".join(r["components"]), "w": r["why"], "h": r["how"]["text"], "enforced": enforced, "d": r["dac"],
           "a": r.get("adr") or []}
    if r.get("instead"):
        out["i"] = r["instead"]
    return out


def client_line(client):
    return f'<div class="for">Prepared for {html.escape(client)}</div>' if client else ""


def render(root=ROOT, bundle=None, client=None):
    bundle = bundle if bundle is not None else load_bundle()
    if bundle is None:
        raise SystemExit(f"shift-left bundle not found at {bundle_dir()}; set SHIFT_LEFT_BUNDLE")
    practices = load_practices(root)
    proposed = {p["id"]: p for p in load_part("proposed-checks", root)}
    dac = {o["id"]: o for o in load_obligations(root)}
    sl_used = sorted({i for r in practices for e in r["enforced_by"] for i in e.get("shift_left", [])})
    gap_used = sorted({e["proposed"] for r in practices for e in r["enforced_by"] if "proposed" in e})
    dac_used = sorted({d for r in practices for d in r["dac"]})
    checks = {i: [bundle[i]["title"], bundle[i]["stage"]] for i in sl_used}
    gaps = {i: [proposed[i]["title"], proposed[i]["stage"], proposed[i]["catches"]] for i in gap_used}
    dacs = {i: [dac[i]["title"], dac[i]["level"], dac[i]["concern"]] for i in dac_used}
    adr = {a["id"]: a for a in load_adrs(root)}
    adrs = {i: [adr[i]["_title"], ADR_BASE + adr[i]["_file"]] for i in sorted({a for r in practices for a in r.get("adr") or []})}
    lines = ["/* Generated by data-platform-catalog/scripts/build_practices_page.py. Do not edit: edit the catalog. */",
             "/* Shift-left checks used on this page (title, stage), from shift-left-bundle/catalog/checks */",
             "const CHECKS = " + js(checks) + ";",
             "/* Proposed checks the bundle does not have yet (title, stage, what it catches), from practices/proposed-checks.yaml */",
             "const GAPS = " + js(gaps) + ";",
             "/* DAC obligations the practices serve (title, level, concern), from dac/obligations */",
             "const DAC = " + js(dacs) + ";",
             "/* ADRs the practices cite (title, link), from adr/ */",
             "const ADRS = " + js(adrs) + ";",
             "/* One entry per practice, from practices/*.yaml, in id order */",
             "const ENTRIES = [",
             ",\n".join(js(entry(r, proposed)) for r in practices),
             "];"]
    return TEMPLATE.read_text().replace("/*@DATA@*/", "\n".join(lines)).replace("<!--@CLIENT@-->", client_line(client))


def arg(argv, flag):
    return argv[argv.index(flag) + 1] if flag in argv else None


def main(argv):
    if "--out" in argv:
        targets = [(Path(arg(argv, "--out")), arg(argv, "--client"))]
    elif "--client" in argv:
        sys.exit("--client goes with --out; for the usual targets set client: in page-targets.local.yaml")
    else:
        targets = TARGETS
    bundle = load_bundle()
    pages = {c: render(bundle=bundle, client=c) for c in {c for _, c in targets}}
    if "--check" in argv:
        stale = [str(t) for t, c in targets if not t.exists() or t.read_text() != pages[c]]
        for t in stale:
            print(f"out of date: {t}")
        sys.exit(1 if stale else 0)
    for t, c in targets:
        if t.parent.is_dir():
            t.write_text(pages[c])
            print(f"wrote {t}" + (f" (client: {c})" if c else ""))
        else:
            print(f"skipped {t}: folder not found")


if __name__ == "__main__":
    main(sys.argv[1:])
